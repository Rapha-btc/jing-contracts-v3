import assert from 'node:assert/strict';
import { initSimnet } from '@stacks/clarinet-sdk';
import { Cl, cvToHex } from '@stacks/transactions';
const simnet = await initSimnet('./Clarinet-creator-stx.toml');
const accounts = simnet.getAccounts();
const owner = accounts.get('deployer');
const creator = accounts.get('wallet_1');
const outsider = accounts.get('wallet_2');
const c = 'creator-escrow-stx-jing';
// A contract principal verifies STX lands in the smart wallet rather than the operating address.
const payout = `${owner}.payout-wallet`;
simnet.deployContract('payout-wallet', '(define-read-only (balance) (stx-get-balance current-contract))', { clarityVersion: 4 }, owner);
const call = (fn, args, sender) => simnet.callPublicFn(c, fn, args, sender).result;
const eq = (actual, expected) => assert.equal(cvToHex(actual), cvToHex(expected));
const price = 10_000_000;
const open = [Cl.principal(creator), Cl.principal(payout), Cl.principal(creator), Cl.principal(payout), Cl.uint(price), Cl.uint(1)];
eq(call('start-round', open, outsider), Cl.error(Cl.uint(100)));
eq(call('start-round', open, owner), Cl.ok(Cl.uint(1)));
eq(call('start-round', open, owner), Cl.error(Cl.uint(103)));
const delivery = [Cl.stringUtf8('https://x.com/creator/status/1'), Cl.buffer(new Uint8Array(32))];
eq(call('submit-delivery', delivery, outsider), Cl.error(Cl.uint(101)));
eq(call('submit-delivery', delivery, creator), Cl.ok(Cl.uint(1)));
eq(call('submit-delivery', delivery, creator), Cl.error(Cl.uint(119)));
eq(call('release', [Cl.uint(1), Cl.bool(true)], creator), Cl.error(Cl.uint(116)));
eq(call('approve', [Cl.uint(1)], outsider), Cl.error(Cl.uint(100)));
eq(call('veto', [Cl.uint(1), Cl.stringUtf8('Revise')], owner), Cl.ok(Cl.bool(true)));
eq(call('amend-delivery', [Cl.uint(1), ...delivery], creator), Cl.ok(Cl.bool(true)));
eq(call('approve', [Cl.uint(1)], owner), Cl.ok(Cl.bool(true)));
eq(call('release', [Cl.uint(1), Cl.bool(true)], outsider), Cl.error(Cl.uint(101)));
eq(call('release', [Cl.uint(1), Cl.bool(false)], creator), Cl.error(Cl.uint(115)));
eq(call('release', [Cl.uint(1), Cl.bool(true)], creator), Cl.ok(Cl.bool(true)));
eq(simnet.callReadOnlyFn('payout-wallet', 'balance', [], owner).result, Cl.uint(price));
eq(call('release', [Cl.uint(1), Cl.bool(true)], creator), Cl.error(Cl.uint(116)));
eq(call('start-round', open, owner), Cl.ok(Cl.uint(2)));
simnet.mineEmptyBurnBlocks(4200);
eq(call('sweep', [Cl.uint(2)], outsider), Cl.error(Cl.uint(100)));
eq(call('sweep', [Cl.uint(2)], owner), Cl.ok(Cl.uint(price)));
eq(call('sweep', [Cl.uint(2)], owner), Cl.error(Cl.uint(113)));
eq(simnet.callReadOnlyFn(c, 'get-escrow-balance', [], owner).result, Cl.uint(0));
eq(call('start-round', open, owner), Cl.ok(Cl.uint(3)));
eq(call('submit-delivery', delivery, creator), Cl.ok(Cl.uint(2)));
simnet.mineEmptyBurnBlocks(288);
eq(call('release', [Cl.uint(2), Cl.bool(true)], creator), Cl.ok(Cl.bool(true)));
eq(simnet.callReadOnlyFn('payout-wallet', 'balance', [], owner).result, Cl.uint(price * 2));
eq(call('start-round', open, owner), Cl.ok(Cl.uint(4)));
eq(call('submit-delivery', delivery, creator), Cl.ok(Cl.uint(3)));
simnet.mineEmptyBurnBlocks(4200);
eq(call('sweep', [Cl.uint(4)], owner), Cl.error(Cl.uint(111)));
eq(call('expire', [Cl.uint(3)], outsider), Cl.error(Cl.uint(117)));
simnet.mineEmptyBurnBlocks(288);
eq(call('expire', [Cl.uint(3)], outsider), Cl.ok(Cl.bool(true)));
eq(call('release', [Cl.uint(3), Cl.bool(true)], creator), Cl.error(Cl.uint(116)));
eq(call('sweep', [Cl.uint(4)], owner), Cl.ok(Cl.uint(price)));
console.log('STX escrow verified: single delivery, authorization, capacity, veto/amend, early approval, terms, smart-wallet payout, no double claim, early next round, refund, timed release.');
