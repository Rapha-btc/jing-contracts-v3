// Builds the RV fuzz copy of kairan-seat-lab-ocifarsito-v2 (production file
// untouched): rewrites the mainnet token principals to the local mocks, LAB and
// FUNDRAISER to devnet wallets, DEADLINE / SEAT_WINDOW to burn heights RV's
// block mining reaches, then appends kairan-seat-lab-ocifarsito-v2.tests.clar.
// Output: tests/rv/kairan-seat-v2/.build/ (ignored) + Clarinet.toml.
//
// Usage: node tests/rv/kairan-seat-v2/build.mjs [deadline] [seatWindow] [restGate]
// restGate: 1-in-N gate on the harness's finish-the-raise actions (0 = never).
import fs from 'node:fs';
import crypto from 'node:crypto';

const DIR = 'tests/rv/kairan-seat-v2';
const OUT = `${DIR}/.build`;
const NAME = 'kairan-seat-lab-ocifarsito-v2';
const SOURCE = `contracts/charity/${NAME}.clar`;
// RV mines 1..ceil(100000/runs) burn blocks after about half the runs, so a
// whole campaign moves the chain roughly 25,000 blocks whatever the run count.
// DEADLINE at ~6,000 keeps the first quarter in the raising phase; a
// 3,000-block seat window leaves room for both the seat and the
// seat-expired failure path.
const [deadline = '6000', seatWindow = '3000', restGate = '8'] = process.argv.slice(2);

const LAB = 'ST1SJ3DTE5DN7X54YDH5D64R3BCB6A2AG2ZQ8YPD5'; // wallet_1
const FUNDRAISER = 'ST2CY5V39NHDPWSXMW9QDT3HC3GD6Q6XX4CFRK9AG'; // wallet_2

const sha = s => crypto.createHash('sha256').update(s).digest('hex');
let source = fs.readFileSync(SOURCE, 'utf8');
const sourceSha = sha(source);
const subs = [
  ["'SP120SBRBQJ00MCWS7TM5R8WJNTTKD5K0HFRC2CNE.usdcx", '.usdcx'],
  ["'SM3VDXK3WZZSA84XXFKAFAF15NNZX32CTSG82JFQ4.sbtc-token", '.sbtc-token'],
  ["(define-constant LAB 'SP2RGCKAQH0ZZD0WEVB38H128DZ1M2S5V3ST871NF)", `(define-constant LAB '${LAB})`],
  ["(define-constant FUNDRAISER 'SP12AVHNBR1K5BRAXP699V66CWK7PQTJJBT2H174F)", `(define-constant FUNDRAISER '${FUNDRAISER})`],
  ['(define-constant DEADLINE u1025386)', `(define-constant DEADLINE u${deadline})`],
  ['(define-constant SEAT_WINDOW u12960)', `(define-constant SEAT_WINDOW u${seatWindow})`],
];
for (const [from, to] of subs) {
  if (!source.includes(from)) throw Error(`source missing ${from}`);
  source = source.replaceAll(from, to);
}
// TERMS strings mention mainnet addresses; only code principals must be gone
const code = source.split('\n').filter(l => !l.trimStart().startsWith('u"') && !l.includes('(concat')).join('\n');
if (/'S[PM][0-9A-Z]{20,}/.test(code)) throw Error('unresolved mainnet principal in fuzz copy');
const GATE = '(define-constant RV_REST_GATE u8)';
let tests = fs.readFileSync(`${DIR}/${NAME}.tests.clar`, 'utf8');
if (!tests.includes(GATE)) throw Error('harness missing RV_REST_GATE');
tests = tests.replace(GATE, `(define-constant RV_REST_GATE u${restGate})`);
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(`${OUT}/${NAME}.clar`, `${source}\n\n${tests}`);

const contract = (name, path) => `\n[contracts.${name}]\npath = "${path}"\nclarity_version = 5\nepoch = "3.4"\n`;
fs.writeFileSync(`${DIR}/Clarinet.toml`,
  `# Generated by tests/rv/kairan-seat-v2/build.mjs. Do not edit.\n[project]\nname = "rv-kairan-seat-v2"\nauthors = []\ntelemetry = false\ncache_dir = "./.cache"\n\n[repl.analysis]\npasses = []\n`
  + contract('usdcx', 'usdcx.clar') + contract('sbtc-token', 'sbtc-token.clar') + contract(NAME, `.build/${NAME}.clar`));
fs.mkdirSync(`${DIR}/settings`, { recursive: true });
fs.copyFileSync('settings/Devnet.toml', `${DIR}/settings/Devnet.toml`);
fs.writeFileSync(`${OUT}/sources.json`, JSON.stringify({ source: SOURCE, sha256: sourceSha, deadline, seatWindow, restGate, lab: LAB, fundraiser: FUNDRAISER }, null, 2) + '\n');
console.log(`built ${OUT}/${NAME}.clar (source sha256 ${sourceSha}, DEADLINE u${deadline}, SEAT_WINDOW u${seatWindow}, RV_REST_GATE u${restGate})`);
