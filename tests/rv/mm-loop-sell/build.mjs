import fs from 'node:fs';
import crypto from 'node:crypto';

const OUT = 'tests/rv/mm-loop-sell/.build';
const OWNER = 'SPV9K21TBFAK4KNRJXF5DFP8N7W46G4V9RCJDC22';
const RUNG_KEYS = ['1', '10', '20', '30', '40', '50', '60', '70', '80', '90'];
const sides = {
  sbtc: {
    source: 'contracts/rfq/yguazu-mm-loop-sell-sbtc.clar',
    rungPrefix: 'jing-buy-stx-',
    mockRung: 'rung-sbtc.clar',
    capFloor: 'buy-back-cap',
    marketOpen: 'stx-on-market',
    openInventory: 'inv-stx',
    marketSide: 'y',
    proceedsInventory: 'inv-stx',
    donationSats: 'u0',
  },
  stx: {
    source: 'contracts/rfq/yguazu-mm-loop-sell-stx.clar',
    rungPrefix: 'jing-sell-stx-',
    mockRung: 'rung-stx.clar',
    capFloor: 'buy-back-floor',
    marketOpen: 'sats-on-market',
    openInventory: 'inv-sats',
    marketSide: 'x',
    proceedsInventory: 'inv-sats',
    donationSats: 'amount',
  },
};
const sha = source => crypto.createHash('sha256').update(source).digest('hex');
const dispatch = side => {
  const names = RUNG_KEYS.map(n => `rung-${n}`);
  const chain = (fn, args, index = 0) => {
    const call = `(contract-call? .vault ${fn} .${names[index]}${args})`;
    return index === names.length - 1 ? call : `(if (is-eq (mod index u10) u${index}) ${call} ${chain(fn, args, index + 1)})`;
  };
  const sell = chain('sell', ' amount');
  const claim = chain('claim', '');
  const withdraw = chain('rung-withdraw', ' amount none');
  const donate = RUNG_KEYS.reduceRight((next, n, index) => {
    const call = `(contract-call? .rung-${n} rv-donate .vault amount)`;
    return index === RUNG_KEYS.length - 1 ? call : `(if (is-eq (mod index u10) u${index}) ${call} ${next})`;
  }, '(err u8999)');
  const amountKey = side.openInventory;
  const marketKey = side.marketOpen;
  const buyBack = `(let ((s (contract-call? .vault get-state)))
    (let ((open (if (> (get ${amountKey} s) (get ${marketKey} s)) (- (get ${amountKey} s) (get ${marketKey} s)) u0)))
      (contract-call? .vault buy-back (if (> open u0) (+ u1 (mod raw open)) u1) (mod spread u10000))))`;
  const fillFn = side.marketSide === 'x' ? 'rv-fill-token-x' : 'rv-fill-token-y';
  const fill = `(contract-call? .market ${fillFn} .vault (+ u1 (mod raw u1000000)) .token)`;
  return `(define-private (rv-sell (index uint) (amount uint)) ${sell})
(define-private (rv-claim (index uint)) ${claim})
(define-private (rv-rung-withdraw (index uint) (amount uint)) ${withdraw})
(define-private (rv-donate (index uint) (amount uint)) ${donate})
(define-private (rv-buy-back (raw uint) (spread uint)) ${buyBack})
(define-private (rv-fill (raw uint)) ${fill})`;
};
const keeperAgent = () => {
  const rungCall = (i = 0) => i === RUNG_KEYS.length
    ? '(err u8999)'
    : `(if (is-eq (mod index u10) u${i}) (contract-call? .vault rung-withdraw .rung-${RUNG_KEYS[i]} amount none) ${rungCall(i + 1)})`;
  return `(define-public (try-withdraw-stx (amount uint)) (contract-call? .vault withdraw-stx amount))
(define-public (try-withdraw-sbtc (amount uint)) (contract-call? .vault withdraw-sbtc amount))
(define-public (try-cancel) (contract-call? .vault cancel-buy-back))
(define-public (try-rung-withdraw (index uint) (amount uint)) ${rungCall()})`;
};
const manifestHeader = name => `# Generated by tests/rv/mm-loop-sell/build.mjs. Do not edit.\n[project]\nname = "rv-mm-loop-sell-${name}"\nauthors = []\ntelemetry = false\ncache_dir = "../../../../.cache"\n\n[repl.analysis]\npasses = []\ncheck_checker = { trusted_sender = false, trusted_caller = false, callee_filter = false }\n`;
const contractConfig = (name, path) => `\n[contracts.${name}]\npath = "${path}"\nclarity_version = 5\nepoch = "3.4"\n`;

fs.mkdirSync(OUT, { recursive: true });
const template = fs.readFileSync('tests/rv/mm-loop-sell/harness.template.clar', 'utf8');
const targets = {};
for (const [sideName, side] of Object.entries(sides)) {
  let source = fs.readFileSync(side.source, 'utf8');
  const originalHash = sha(source);
  const substitutions = {
    [`'${OWNER}.jing-rung-deposit-trait.rung-trait`]: '.rung-trait.rung-trait',
    [`'${OWNER}.markets-sbtc-stx-jing-v6-4`]: '.market',
    "'SM3VDXK3WZZSA84XXFKAFAF15NNZX32CTSG82JFQ4.sbtc-token": '.token',
    '"sbtc-token"': '"token"',
  };
  if (sideName === 'sbtc') substitutions["'SM1793C4R5PZ4NS4VQ4WMP7SKKYVH8JZEWSZ9HCCR.token-stx-v-1-2"] = '.token';
  for (const n of [...RUNG_KEYS].sort((a, b) => b.length - a.length)) substitutions[`'${OWNER}.${side.rungPrefix}${n}`] = `.rung-${n}`;
  for (const [from, to] of Object.entries(substitutions)) {
    if (!source.includes(from)) throw Error(`${sideName} source missing dependency ${from}`);
    source = source.replaceAll(from, to);
  }
  const ownerVar = '(define-data-var owner principal tx-sender)';
  const keeperVar = '(define-data-var keeper (optional principal) none)';
  if (!source.includes(ownerVar) || !source.includes(keeperVar)) throw Error(`${sideName} source missing owner/keeper initializers`);
  source = source.replace(ownerVar, `(define-data-var owner principal .rv-${sideName})`);
  source = source.replace(keeperVar, '(define-data-var keeper (optional principal) (some .keeper-agent))');
  if (/'S[PM][0-9A-Z]{20,}\./.test(source)) throw Error(`${sideName} source contains unresolved mainnet principal`);
  const targetPath = `${OUT}/${sideName}-vault.clar`;
  fs.writeFileSync(targetPath, source);
  const targetName = `vault`;
  let harness = template
    .replace('@@TARGET_DISPATCH@@', dispatch(side))
    .replace('@@KEEPER_AGENT@@', keeperAgent())
    .replaceAll('@@CAP_OR_FLOOR@@', side.capFloor)
    .replaceAll('@@MARKET_OPEN@@', side.marketOpen)
    .replaceAll('@@OPEN_INVENTORY@@', side.openInventory);
  harness = harness
    .replaceAll('@@PROCEEDS_INVENTORY@@', side.proceedsInventory)
    .replaceAll('@@DONATION_SATS@@', side.donationSats);
  harness = harness.replace('(<= (get buy-back-floor s) (get vwap-sell s))', '(>= (get buy-back-floor s) (get vwap-sell s))');
  const aliases = [...harness.matchAll(/\(define-public \((test-[a-z0-9-]+)((?: \([a-z0-9-]+ [^()]+\))*)\)/g)].map((m) => {
    const args = m[2];
    const params = [...args.matchAll(/\(([a-z0-9-]+) /g)].map(x => x[1]);
    return `(define-public (rv-${m[1]}${args}) (${m[1]}${params.map(p => ` ${p}`).join('')}))`;
  }).join('\n');
  harness += `\n;; RV invariant mode exercises the same action functions through these aliases.\n${aliases}\n`;
  const harnessPath = `${OUT}/${sideName}-harness.clar`;
  fs.writeFileSync(harnessPath, harness);
  const rungSource = fs.readFileSync(`tests/rv/mm-loop-sell/${side.mockRung}`, 'utf8');
  const keeperPath = `${OUT}/${sideName}-keeper.clar`;
  fs.writeFileSync(keeperPath, keeperAgent());
  const projectDir = `tests/rv/mm-loop-sell/${sideName}`;
  fs.mkdirSync(projectDir, { recursive: true });
  fs.mkdirSync(`${projectDir}/settings`, { recursive: true });
  fs.copyFileSync('settings/Devnet.toml', `${projectDir}/settings/Devnet.toml`);
  const configs = [
    ['sip-010-trait', '../sip-010-trait.clar'],
    ['rung-trait', '../rung-trait.clar'],
    ['token', '../token.clar'],
    ['market', '../market.clar'],
    ...RUNG_KEYS.map(n => [`rung-${n}`, `../.build/${sideName}-rung.clar`]),
    ['vault', `../.build/${sideName}-vault.clar`],
    ['keeper-agent', `../.build/${sideName}-keeper.clar`],
    [`rv-${sideName}`, `../.build/${sideName}-harness.clar`],
  ];
  fs.writeFileSync(`${projectDir}/Clarinet.toml`, manifestHeader(sideName) + configs.map(([n, p]) => contractConfig(n, p)).join(''));
  fs.writeFileSync(`${OUT}/${sideName}-rung.clar`, rungSource);
  targets[sideName] = { source: side.source, sha256: originalHash, generatedSha256: sha(source), targetPath, harnessPath };
}
fs.writeFileSync(`${OUT}/sources.json`, JSON.stringify({ targets, rungKeys: RUNG_KEYS }, null, 2) + '\n');
console.log(`built RV vault fixtures under ${OUT}`);
