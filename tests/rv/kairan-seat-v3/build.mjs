// Builds the RV fuzz copy of kairan-seat-lab-ocifarsito-v3 (production file
// untouched): rewrites the mainnet sBTC principal to the local mock, LAB and
// FUNDRAISER to devnet wallets, then appends kairan-seat-lab-ocifarsito-v3.tests.clar.
// OWNER stays the deployer.
// Output: tests/rv/kairan-seat-v3/.build/ (ignored) + Clarinet.toml.
//
// Usage: node tests/rv/kairan-seat-v3/build.mjs [releaseGate]
// releaseGate: 1-in-N gate on the harness's release-the-current-request
// action (0 = never), so the open phase sees many deposits and requests.
import fs from 'node:fs';
import crypto from 'node:crypto';

const DIR = 'tests/rv/kairan-seat-v3';
const OUT = `${DIR}/.build`;
const NAME = 'kairan-seat-lab-ocifarsito-v3';
const SOURCE = `contracts/charity/${NAME}.clar`;
const [releaseGate = '16'] = process.argv.slice(2);

const LAB = 'ST1SJ3DTE5DN7X54YDH5D64R3BCB6A2AG2ZQ8YPD5'; // wallet_1
const FUNDRAISER = 'ST2CY5V39NHDPWSXMW9QDT3HC3GD6Q6XX4CFRK9AG'; // wallet_2

const sha = s => crypto.createHash('sha256').update(s).digest('hex');
let source = fs.readFileSync(SOURCE, 'utf8');
const sourceSha = sha(source);
const subs = [
  ["'SM3VDXK3WZZSA84XXFKAFAF15NNZX32CTSG82JFQ4.sbtc-token", '.sbtc-token'],
  ["(define-constant LAB 'SP2RGCKAQH0ZZD0WEVB38H128DZ1M2S5V3ST871NF)", `(define-constant LAB '${LAB})`],
  ["(define-constant FUNDRAISER 'SP12AVHNBR1K5BRAXP699V66CWK7PQTJJBT2H174F)", `(define-constant FUNDRAISER '${FUNDRAISER})`],
];
for (const [from, to] of subs) {
  if (!source.includes(from)) throw Error(`source missing ${from}`);
  source = source.replaceAll(from, to);
}
// TERMS strings mention mainnet addresses; only code principals must be gone
const code = source.split('\n').filter(l => !l.trimStart().startsWith('u"') && !l.includes('(concat')).join('\n');
if (/'S[PM][0-9A-Z]{20,}/.test(code)) throw Error('unresolved mainnet principal in fuzz copy');
const GATE = '(define-constant RV_RELEASE_GATE u16)';
let tests = fs.readFileSync(`${DIR}/${NAME}.tests.clar`, 'utf8');
if (!tests.includes(GATE)) throw Error('harness missing RV_RELEASE_GATE');
tests = tests.replace(GATE, `(define-constant RV_RELEASE_GATE u${releaseGate})`);
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(`${OUT}/${NAME}.clar`, `${source}\n\n${tests}`);

const contract = (name, path) => `\n[contracts.${name}]\npath = "${path}"\nclarity_version = 5\nepoch = "3.4"\n`;
fs.writeFileSync(`${DIR}/Clarinet.toml`,
  `# Generated by tests/rv/kairan-seat-v3/build.mjs. Do not edit.\n[project]\nname = "rv-kairan-seat-v3"\nauthors = []\ntelemetry = false\ncache_dir = "./.cache"\n\n[repl.analysis]\npasses = []\n`
  + contract('sbtc-token', 'sbtc-token.clar') + contract(NAME, `.build/${NAME}.clar`));
fs.mkdirSync(`${DIR}/settings`, { recursive: true });
fs.copyFileSync('settings/Devnet.toml', `${DIR}/settings/Devnet.toml`);
fs.writeFileSync(`${OUT}/sources.json`, JSON.stringify({ source: SOURCE, sha256: sourceSha, releaseGate, lab: LAB, fundraiser: FUNDRAISER }, null, 2) + '\n');
console.log(`built ${OUT}/${NAME}.clar (source sha256 ${sourceSha}, RV_RELEASE_GATE u${releaseGate})`);
