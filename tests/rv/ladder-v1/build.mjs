// RV stack for the FINAL pooled-maker set: jing-ladder-dispatch (the RV
// target) on four real miner-band rungs (jing-buy/sell-stx-core-spread-v1 at
// spreads 20 and 50), the real jing-ladder-v1, the real jing-core-v6 and the
// final markets-sbtc-stx-jing-v6-3.
//
// Production sources are only rewritten for dependency identities (the same
// substitution table as tests/unit/integration-v6-3/build.mjs: mainnet
// principals -> simnet fixtures). Core and ladder deploy byte-identical.
// Test-only code is APPENDED after the production text:
//   - each rung gets a read-only inspection block (rv-raw / rv-vars /
//     rv-reserve) so the invariants can sum over its private positions map;
//   - the RV target is a separate generated contract, rv-ladder-harness
//     (harness.mjs): wrappers, ghost ledger, properties, invariants. The
//     dispatcher itself is production text with dependency substitutions.
// The build asserts that every generated file starts with the substituted
// production text, and records the source hashes in sources.json.
import fs from 'node:fs';
import crypto from 'node:crypto';
import { harness, RUNGS } from './harness.mjs';

const dir = 'tests/rv/ladder-v1';
const out = 'tests/rv/.build/ladder-v1';
const owner = 'ST1PQHQKV0RJXZFY1DGX8MNSNYVE3VGZJSRTPGZGM';
export const substitutions = {
  "'SP3FBR2AGK5H9QBDH3EEN6DF8EK8JY7RX8QJ5SVTE.sip-010-trait-ft-standard.sip-010-trait": '.sip-010-trait.sip-010-trait',
  "'SPMV5HDZ4EMB8XY7HAYT3XW0DF7DZ4E8XEG2J1T8.pyth-lazer-oracle": '.oracle',
  "'SPMV5HDZ4EMB8XY7HAYT3XW0DF7DZ4E8XEG2J1T8.pyth-lazer-decoder-v1": '.oracle',
  "'SPV9K21TBFAK4KNRJXF5DFP8N7W46G4V9RCJDC22.markets-sbtc-stx-jing-v6-3": `'${owner}.market`,
  "'SPV9K21TBFAK4KNRJXF5DFP8N7W46G4V9RCJDC22.jing-ladder-v1": `'${owner}.jing-ladder-v1`,
  "'SPV9K21TBFAK4KNRJXF5DFP8N7W46G4V9RCJDC22.rfq-sbtc-stx-jing-v2-3": `'${owner}.miner-oracle`,
  "'SM3VDXK3WZZSA84XXFKAFAF15NNZX32CTSG82JFQ4.sbtc-token": `'${owner}.token`,
  "'SM1793C4R5PZ4NS4VQ4WMP7SKKYVH8JZEWSZ9HCCR.token-stx-v-1-2": `'${owner}.asset-stx`,
  '"sbtc-token"': '"token"',
};
const sha = s => crypto.createHash('sha256').update(s).digest('hex');
const inspect = buy => `
;; ===== RV inspection, appended by tests/rv/ladder-v1/build.mjs (test-only) =====
(define-read-only (rv-raw (who principal)) (map-get? positions who))
(define-read-only (rv-reserve (e uint)) (map-get? epoch-reserve e))
(define-read-only (rv-vars)
  {held: (var-get ${buy ? 'held-sats' : 'held-ustx'}),
   reserved: (var-get ${buy ? 'reserved-sats' : 'reserved-ustx'}),
   accounted: (var-get ${buy ? 'stx-accounted' : 'sats-accounted'}),
   current-proceeds: (var-get current-proceeds), carry: (var-get proceeds-carry),
   epoch: (var-get epoch), scale: (var-get scale), total: (var-get total-shares),
   members: (var-get members), unfilled: (var-get unfilled-index),
   pindex: (var-get proceeds-index), paused: (var-get push-paused)})
`;

fs.mkdirSync(out, { recursive: true });
fs.mkdirSync(`${dir}/settings`, { recursive: true });
fs.copyFileSync('settings/Devnet.toml', `${dir}/settings/Devnet.toml`);
const sources = {};
function generate(name, suffix) {
  const path = `contracts/${name}.clar`, source = fs.readFileSync(path, 'utf8');
  let prefix = source;
  for (const [from, to] of Object.entries(substitutions)) prefix = prefix.replaceAll(from, to);
  if (/'S[PM][0-9A-Z]{20,}\./.test(prefix)) throw Error(`${name}: unsubstituted mainnet principal`);
  const text = prefix + (suffix ?? '');
  if (!text.startsWith(prefix)) throw Error(name);
  fs.writeFileSync(`${out}/${name}.clar`, text);
  sources[name] = { path, sha256: sha(source), prefixSha256: sha(prefix) };
}
generate('markets-sbtc-stx-jing-v6-3');
generate('jing-buy-stx-core-spread-v1', inspect(true));
generate('jing-sell-stx-core-spread-v1', inspect(false));
generate('jing-ladder-dispatch');
fs.writeFileSync(`${out}/rv-ladder-harness.clar`, harness());
for (const name of ['jing-core-v6', 'jing-ladder-v1', 'jing-rung-deposit-trait'])
  sources[name] = { path: `contracts/${name}.clar`, sha256: sha(fs.readFileSync(`contracts/${name}.clar`, 'utf8')), byteIdentical: true };
fs.writeFileSync(`${out}/sources.json`, JSON.stringify({ sources, substitutions }, null, 2) + '\n');

