const paths = { market: 'contracts/markets-sbtc-stx-jing-v6-3.clar', router: 'contracts/swap-router-sbtc-stx-jing-v5-3.clar' };
const sha = s => crypto.createHash('sha256').update(s).digest('hex');
fs.mkdirSync(out, { recursive: true });
fs.mkdirSync(`${dir}/settings`, { recursive: true });
fs.copyFileSync('settings/Devnet.toml', `${dir}/settings/Devnet.toml`);
const sources = {};
for (const [name, path] of Object.entries(paths)) {
  const source = fs.readFileSync(path, 'utf8'); let g = source;
  for (const [a, b] of Object.entries(deps[name])) { if (!g.includes(a)) throw Error(`missing ${a}`); g = g.replaceAll(a, b); }
  if (/'S[PM][0-9A-Z]{20,}\./.test(g)) throw Error(`${name}: unsubstituted mainnet principal`);
  fs.writeFileSync(`${out}/${name}.clar`, g);
  sources[name] = { path, sha256: sha(source), generatedSha256: sha(g) };
}
sources['jing-core-v6'] = { path: 'contracts/jing-core-v6.clar', sha256: sha(fs.readFileSync('contracts/jing-core-v6.clar', 'utf8')), byteIdentical: true };
fs.writeFileSync(`${out}/rv-router-harness.clar`, harness());
fs.writeFileSync(`${out}/sources.json`, JSON.stringify({ sources, deps }, null, 2) + '\n');
const c = (n, p) => `\n[contracts.${n}]\npath = "${p}"\nclarity_version = 5\nepoch = "3.4"\n`;
let m = '# Generated by tests/rv/router-v5-3/build.mjs. Do not edit.\n[project]\nname = "rv-router-v5-3"\nauthors = []\ntelemetry = false\ncache_dir = "../../../.cache"\n';
