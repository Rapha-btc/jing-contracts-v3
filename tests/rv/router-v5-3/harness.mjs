// Generates the RV target `rv-router-harness` for swap-router-sbtc-stx-jing-v5-3.
// Same conventions as tests/rv/ladder-v1/harness.mjs: test-* properties
// ((ok true) checked, (ok false) refused and rolled back behind the router's
// contract-call? boundary, (err u96xx) violated) and generated rv-* aliases
// that latch `rv-valid` for invariant mode.
//
// The router is called WITHOUT as-contract: tx-sender stays the RV account
// through every leg, as it does for a wallet on mainnet. Properties checked on
// every successful router call, measured on balances, never on what venues
// report (the venue fixtures can be set to over-report, `inflate`):
//   - the user's bought-asset delta == receipt `out` >= min-out
//   - the user's sold-asset delta == sum of the four legs' `in`
//   - legs + unsold == amount (nothing silently lost)
//   - the router and this harness hold no sBTC and no STX
//   - smart swaps: the average price over all legs respects `limit-price`
export const OWNER = 'ST1PQHQKV0RJXZFY1DGX8MNSNYVE3VGZJSRTPGZGM';
export const VENUES = ['dlmm', 'dlmm-2', 'dlmm-3', 'xyk', 'velar'];

export function harness() {
  let s = `;; Generated by tests/rv/router-v5-3/harness.mjs. Do not edit. Not a production contract.
(define-map context (string-ascii 100) {called: uint})
(define-public (update-context (function-name (string-ascii 100)) (called uint))
  (ok (map-set context function-name {called: called})))
(define-constant RV-MAXU u340282366920938463463374607431768211455)
(define-constant PRICE_SCALE u10000000000)
(define-data-var rv-valid bool true)
(define-data-var rv-fail-code uint u0)
(define-map rv-count (string-ascii 48) uint)
(define-read-only (rv-get-count (k (string-ascii 48))) (default-to u0 (map-get? rv-count k)))
(define-read-only (rv-status) {valid: (var-get rv-valid), code: (var-get rv-fail-code)})
(define-private (rv-bump (k (string-ascii 48)))
  (begin (print {rv-success: k}) (map-set rv-count k (+ u1 (rv-get-count k)))))
(define-private (tok (who principal)) (unwrap-panic (contract-call? .token get-balance who)))
(define-private (sold-bal (x bool) (who principal)) (if x (tok who) (stx-get-balance who)))
(define-private (bought-bal (x bool) (who principal)) (if x (stx-get-balance who) (tok who)))
(define-private (mid) (contract-call? .oracle get-mid))
(define-read-only (router-empty)
  (and (is-eq (tok .router) u0) (is-eq (stx-get-balance .router) u0)
       (is-eq (tok current-contract) u0) (is-eq (stx-get-balance current-contract) u0)))

;; the receipt against the wallet, for every successful router call
(define-private (check-receipt (x bool) (amount uint) (min-out uint) (s0 uint) (b0 uint)
    (r {jing-ok: bool, jing-in: uint, jing-out: uint, dlmm-in: uint, dlmm-out: uint, xyk-in: uint,
        xyk-out: uint, velar-in: uint, velar-out: uint, unsold: uint, out: uint}))
  (let ((who tx-sender) (s1 (sold-bal x who)) (b1 (bought-bal x who))
        (spent (+ (get jing-in r) (get dlmm-in r) (get xyk-in r) (get velar-in r))))
    ;; on any violation, print the inputs (the alias commits the print)
    (or (and (<= s1 s0) (is-eq (- s0 s1) spent) (>= b1 b0) (is-eq (- b1 b0) (get out r)) (>= (get out r) min-out)
             (is-eq (+ spent (get unsold r)) amount) (router-empty))
        (begin (print {rv-violation: true, x: x, amount: amount, min-out: min-out, s0: s0, s1: s1, b0: b0, b1: b1, receipt: r,
                       router-tok: (tok .router), router-stx: (stx-get-balance .router)}) false))
    (asserts! (<= s1 s0) (err u9600))
    (asserts! (is-eq (- s0 s1) spent) (err u9601))
    (asserts! (>= b1 b0) (err u9606))
    (asserts! (is-eq (- b1 b0) (get out r)) (err u9602))
    (asserts! (>= (get out r) min-out) (err u9603))
    (asserts! (is-eq (+ spent (get unsold r)) amount) (err u9604))
    (asserts! (router-empty) (err u9605))
    (ok spent)))

;; A user who also rests on the book is paid as a maker by the settlement the
;; swap runs, in the same balances the router measures (seen in RV: 3 sats of
;; a y bid's distribution counted as "less sbtc sold"). Wallet-delta properties
;; only hold for a user with no market position, so such a user is discarded.
(define-private (has-book (who principal))
  (let ((c (contract-call? .market get-current-cycle)))
    (> (+ (contract-call? .market get-token-x-deposit c who) (contract-call? .market get-token-y-deposit c who)
          (contract-call? .market get-token-x-parked who) (contract-call? .market get-token-y-parked who)
          (default-to u0 (get amount (contract-call? .market get-token-x-pending-deposit who)))
          (default-to u0 (get amount (contract-call? .market get-token-y-pending-deposit who))))
       u0)))
;; what a fair fill pays at the mid, for the min-out modes
(define-private (fair (x bool) (amount uint) (m uint))
  (if x (/ (* amount m) PRICE_SCALE) (/ (* amount PRICE_SCALE) m)))
(define-private (min-out-of (mode uint) (fv uint))
  (if (is-eq mode u0) u0 (if (is-eq mode u1) (/ (* fv u9000) u10000) (if (is-eq mode u2) (/ (* fv u9950) u10000) RV-MAXU))))

;; Manual split: amount and four weights from the random naturals; the
;; fallback venue, the AMM minimums and min-out each in a few modes, some
;; of them impossible on purpose (an impossible minimum must revert).
(define-public (test-manual (x bool) (raw uint) (split uint) (fb uint) (mins uint) (mo uint) (lim uint))
  (let ((m (mid))
        (amount (if x (+ u200 (mod raw u3000000)) (+ u20000 (mod raw u9000000000))))
        (wj (mod split u7)) (wd (mod (/ split u7) u7)) (wx (mod (/ split u49) u7)) (wv (mod (/ split u343) u7))
        (wsum (+ wj wd wx wv))
        (j (if (is-eq wsum u0) amount (/ (* amount wj) wsum)))
        (d (if (is-eq wsum u0) u0 (/ (* amount wd) wsum)))
        (xk (if (is-eq wsum u0) u0 (/ (* amount wx) wsum)))
        (v (- amount (+ j d xk)))
        (fbm (mod fb u5))
        (fallback (if (is-eq fbm u0) none (if (is-eq fbm u4) (some u9) (some fbm))))
        (mm (mod mins u3))
        (mn (lambda-free-mins x mm d xk v m))
        (limit (if x (/ (* m (- u10000 (mod lim u200))) u10000) (/ (* m (+ u10000 (mod lim u200))) u10000)))
        (min-out (min-out-of (mod mo u4) (fair x amount m)))
        (who tx-sender) (s0 (sold-bal x who)) (b0 (bought-bal x who))
        (upd (if (is-eq (mod lim u13) u0) none (some 0x00))))
    (asserts! (not (has-book who)) (ok false))
    (match (if x
             (contract-call? .router swap-sbtc-for-stx amount j limit upd fallback {dlmm: d, xyk: xk, velar: v} mn min-out)
             (contract-call? .router swap-stx-for-sbtc amount j limit upd fallback {dlmm: d, xyk: xk, velar: v} mn min-out))
      r (begin
          (try! (check-receipt x amount min-out s0 b0 r))
          (asserts! (not (is-eq fbm u4)) (err u9610))
          (asserts! (not (and (> j u0) (is-none upd))) (err u9611))
          (rv-bump (if (get jing-ok r) "manual-with-book" "manual-amm-only"))
          (and (> (get unsold r) u0) (rv-bump "manual-unsold"))
          (ok true))
      e (begin (rv-bump (if (is-eq e u3002) "manual-refused-min-out" "manual-refused")) (ok false)))))
(define-private (lambda-free-mins (x bool) (mm uint) (d uint) (xk uint) (v uint) (m uint))
  (if (is-eq mm u0) {dlmm: u0, xyk: u0, velar: u0}
    (if (is-eq mm u1)
      {dlmm: (/ (* (fair x d m) u9000) u10000), xyk: (/ (* (fair x xk m) u9000) u10000), velar: (/ (* (fair x v m) u9000) u10000)}
      {dlmm: (* u2 (fair x d m)), xyk: (* u2 (fair x xk m)), velar: (* u2 (fair x v m))})))

;; Smart: one limit; the router sizes every leg on chain. The caller's mid
;; hint is right, or off by 1% either way (it is only a sizing hint).
(define-public (test-smart (x bool) (raw uint) (lim uint) (skew uint) (mo uint))
  (let ((m (mid))
        (amount (if x (+ u200 (mod raw u3000000)) (+ u20000 (mod raw u9000000000))))
        (limit (if x (/ (* m (- u10000 (mod lim u400))) u10000) (/ (* m (+ u10000 (mod lim u400))) u10000)))
        (sk (mod skew u3))
        (hint (if (is-eq sk u0) m (if (is-eq sk u1) (/ (* m u10100) u10000) (/ (* m u9900) u10000))))
        (upd (if (is-eq (mod skew u11) u0) none (some 0x00)))
        (min-out (min-out-of (mod mo u4) (fair x amount m)))
        (who tx-sender) (s0 (sold-bal x who)) (b0 (bought-bal x who)))
    (asserts! (not (has-book who)) (ok false))
    (match (if x
             (contract-call? .router smart-swap-sbtc-for-stx amount limit upd hint min-out)
             (contract-call? .router smart-swap-stx-for-sbtc amount limit upd hint min-out))
      r (let ((spent (try! (check-receipt x amount min-out s0 b0 r))) (out (get out r)))
          ;; the average price of all legs together respects the limit (a few
          ;; units of rounding: each of up to six legs floors once)
          ;; Strict form fails by up to ONE base unit of the sold asset: the
          ;; market floors net = amount * 1e4 / (1e4 + bps), so the rebate a
          ;; mid-cross pays its makers is a ceiling the router's net-limit rule
          ;; does not see (RV seed 241025, tests/rv-repro-router-smart-limit.test.ts).
          ;; The property allows exactly that unit and counts each use of it.
          (asserts! (if x (>= (+ (* (+ out u8) PRICE_SCALE) limit) (* spent limit)) (>= (+ (* (+ out u8) limit) PRICE_SCALE) (* spent PRICE_SCALE))) (err u9620))
          (and (not (if x (>= (* (+ out u8) PRICE_SCALE) (* spent limit)) (>= (* (+ out u8) limit) (* spent PRICE_SCALE))))
               (rv-bump "smart-under-limit-by-1-unit"))
          (asserts! (not (and (get jing-ok r) (is-none upd))) (err u9621))
          (rv-bump (if (get jing-ok r) "smart-with-book" "smart-amm-only"))
          (and (> (get dlmm-in r) u0) (rv-bump "smart-dlmm"))
          (and (> (+ (get xyk-in r) (get velar-in r)) u0) (rv-bump "smart-cp"))
          (and (> (get unsold r) u0) (rv-bump "smart-unsold"))
          (ok true))
      e (begin (rv-bump (if (is-eq e u3002) "smart-refused-min-out" "smart-refused")) (ok false)))))

;; ------------------------------------------------ the book and the venues
(define-constant RV-MAKERS (list 'ST1PQHQKV0RJXZFY1DGX8MNSNYVE3VGZJSRTPGZGM 'ST1SJ3DTE5DN7X54YDH5D64R3BCB6A2AG2ZQ8YPD5
  'ST2CY5V39NHDPWSXMW9QDT3HC3GD6Q6XX4CFRK9AG 'ST2JHG361ZXG51QTKY2NQCVBPPRRE2KZB1HR05NNC 'ST2NEB84ASENDXKYGJPQW86YXQCEFEX2ZQPG87ND))
;; five accounts make the book; the other four stay clean takers
(define-public (test-maker (x bool) (raw uint) (lim uint))
  (let ((m (mid)))
    (asserts! (is-some (index-of? RV-MAKERS tx-sender)) (ok false))
    (match (if x
             (contract-call? .market deposit-token-x (+ u100 (mod raw u500000)) (/ (* m (+ u10005 (mod lim u150))) u10000) none .token "token")
             (contract-call? .market deposit-token-y (+ u10000 (mod raw u1500000000)) (/ (* m (- u9995 (mod lim u150))) u10000) none .asset-stx "token"))
      okv (begin (asserts! (router-empty) (err u9605)) (rv-bump "maker") (ok true))
      e (ok false))))
(define-public (test-admit (who principal) (x bool))
  (match (if x
           (contract-call? .market settle-token-x-deposit who 0x00 .token "token")
           (contract-call? .market settle-token-y-deposit who 0x00 .asset-stx "token"))
    okv (begin (asserts! (router-empty) (err u9605)) (rv-bump "admit") (ok true))
    e (ok false)))
(define-public (test-cancel (x bool))
  (match (if x (contract-call? .market cancel-token-x-deposit .token "token") (contract-call? .market cancel-token-y-deposit .asset-stx "token"))
    okv (begin (asserts! (router-empty) (err u9605)) (rv-bump "cancel") (ok true))
    e (ok false)))
(define-public (test-mid (raw uint))
  (begin (try! (contract-call? .oracle set-mid (+ u30400000000000 (* (mod raw u3200) u1000000000)))) (rv-bump "mid") (ok true)))
;; venue state (owner only, so effective when RV picks the deployer): reserves
;; drift, fees change, and a venue may over-report its output (inflate)
(define-public (test-venue (k uint) (raw uint) (fee uint) (lie uint))
  (let ((v (mod k u${VENUES.length})) (sats (+ u1000000 (mod raw u200000000)))
        (ustx (/ (* (+ u1000000 (mod raw u200000000)) (mid)) PRICE_SCALE))
        (f (mod fee u100)) (inflate (if (is-eq (mod lie u4) u0) (mod lie u1000) u0)))
    (asserts! true (err u0))
    (match ${VENUES.map((n, i) => i < VENUES.length - 1 ? `(if (is-eq v u${i}) (venue-${n} sats ustx f inflate)` : `(venue-${n} sats ustx f inflate)`).join(' ')}${')'.repeat(VENUES.length - 1)}
      okv (begin (rv-bump "venue") (ok true))
      e (ok false))))
${VENUES.map(n => `(define-private (venue-${n} (sats uint) (ustx uint) (f uint) (inflate uint))
  (begin
    (try! (contract-call? .${n} configure sats ustx false f f))
    (try! (contract-call? .${n} set-inflate inflate))
    ${n.startsWith('dlmm') ? `(try! (contract-call? .${n} configure-dlmm 0 (/ (* sats u100000000) (if (> ustx u0) ustx u1)) u15 RV-MAXU))` : ''}
    (ok true)))`).join('\n')}

;; ================================================================ invariants
(define-read-only (invariant-all)
  (and (var-get rv-valid) (router-empty)))
`;
  for (const m of s.matchAll(/\(define-public \((test-[a-z0-9-]+)((?: \([a-z0-9-]+ (?:uint|bool|principal)\))*)\)/g)) {
    const [, name, args] = m, params = [...args.matchAll(/\(([a-z0-9-]+) /g)].map(x => x[1]);
    s += `(define-public (${name.replace('test-', 'rv-')}${args}) (match (${name}${params.map(p => ' ' + p).join('')}) rv-res (ok rv-res) rv-code (begin (var-set rv-valid false) (var-set rv-fail-code rv-code) (ok false))))\n`;
  }
  return s;
}
